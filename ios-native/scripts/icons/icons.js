// 齿轮：8 齿，圆角由 linejoin 给
function gear(cx, cy, R, r0, n = 8) {
  const pts = [];
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    const step = Math.PI * 2 / n;
    const o = step * 0.17, ii = step * 0.3;
    pts.push([a - ii, r0], [a - o, R], [a + o, R], [a + ii, r0]);
  }
  return 'M' + pts.map(([a, rr]) => `${f1(cx + rr * Math.sin(a))} ${f1(cy - rr * Math.cos(a))}`).join('L') + 'Z';
}
function star(cx, cy, R, r0) {
  const pts = [];
  for (let i = 0; i < 10; i++) {
    const a = (i / 10) * Math.PI * 2;
    const rr = i % 2 ? r0 : R;
    pts.push(`${f1(cx + rr * Math.sin(a))} ${f1(cy - rr * Math.cos(a))}`);
  }
  return 'M' + pts.join('L') + 'Z';
}
function rays(cx, cy, r1, r2, n = 8) {
  let d = '';
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    d += `M${f1(cx + r1 * Math.sin(a))} ${f1(cy - r1 * Math.cos(a))}L${f1(cx + r2 * Math.sin(a))} ${f1(cy - r2 * Math.cos(a))}`;
  }
  return d;
}
function dots(cx, cy, rr, size, n = 8) {
  let s = '';
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    s += cf(f1(cx + rr * Math.sin(a)), f1(cy - rr * Math.cos(a)), size);
  }
  return s;
}

