#!/usr/bin/env python3
"""把 icons.js 里的线框图标生成为 Xcode 自定义符号（.symbolset）。

SF Symbols 模板只接受填充形状，不接受描边，所以这里先把每个图标在 2400×2400 上渲染成
黑底白图（镂空部分画黑），再沿 50% 灰度等值线描出轮廓（外轮廓、孔洞方向相反，
nonzero / evenodd 两种填充规则下都正确），最后套进只含 Regular-M 的静态模板。

依赖：node、rsvg-convert、numpy、scikit-image、Pillow。只在本机重新生成图标时需要，构建不需要。

用法：python3 ios-native/scripts/icons/build-symbols.py
"""
import io
import json
import pathlib
import shutil
import subprocess
import sys

import numpy as np
from PIL import Image
from skimage import measure

HERE = pathlib.Path(__file__).resolve().parent
ASSETS = HERE.parents[1] / "HPlayer" / "Assets.xcassets"
OUT = ASSETS / "Icons"
PX = 100                      # 每个网格单位渲染多少像素
SIZE = 24 * PX
TOLERANCE = 0.6               # 轮廓简化容差（像素）= 0.006 网格单位

# 模板（100pt 排版）：SF Pro 的大写线高 70.459。
BASELINE = {"S": 696.0, "M": 1126.0, "L": 1556.0}
CAP = 70.459
# 一个网格单位对应多少模板单位：让外径 18.6 的圆约等于系统 "circle" 符号的 115 单位，
# 和原来的 SF Symbols 在同样字号下大小一致，1.6 线宽约等于 Medium 字重的笔画。
SCALE = 6.2
SIDE = 3.0                    # 左右边距（模板单位）
ORIGIN_X = 1400.0

# 不在 AppIcon 里、只在原型里出现的变体不生成
SKIP = {"search_active"}


def load_icons() -> dict:
    script = f"const {{I}} = require({json.dumps(str(HERE / 'icons.js'))}); process.stdout.write(JSON.stringify(I));"
    return json.loads(subprocess.check_output(["node", "-e", script]))


def render_svg(inner: str) -> str:
    """把带 class 的片段改成显式属性：墨迹白、镂空黑，rsvg 不需要支持 CSS。"""
    body = (inner
            .replace('class="f" stroke-linejoin="round" style="stroke:currentColor;stroke-width:1.4"',
                     'fill="#fff" stroke="#fff" stroke-width="1.4" stroke-linejoin="round"')
            .replace('class="f"', 'fill="#fff" stroke="none"')
            .replace('class="kf"', 'fill="#000" stroke="none"')
            .replace('class="k"', 'stroke="#000"'))
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="{SIZE}" height="{SIZE}">'
            f'<rect width="24" height="24" fill="#000"/>'
            f'<g fill="none" stroke="#fff" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">{body}</g></svg>')


def raster(svg: str) -> np.ndarray:
    png = subprocess.check_output(["rsvg-convert", "-w", str(SIZE), "-h", str(SIZE)], input=svg.encode())
    img = Image.open(io.BytesIO(png)).convert("L")
    return np.asarray(img, dtype=np.float64) / 255.0


def contours(coverage: np.ndarray) -> list:
    padded = np.pad(coverage, 1)  # 保证每条等值线都闭合
    result = []
    for c in measure.find_contours(padded, 0.5, positive_orientation="high"):
        c = measure.approximate_polygon(c, tolerance=TOLERANCE)
        if len(c) < 4:
            continue
        # (row, col) → 网格单位 (x, y)
        pts = [((col - 1) / PX, (row - 1) / PX) for row, col in c]
        result.append(pts)
    return result


def fmt(v: float) -> str:
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def symbol_svg(name: str, polys: list) -> str:
    xs = [x for poly in polys for x, _ in poly]
    half = max(12 - min(xs), max(xs) - 12)          # 以 24 网格中线对称，保留设计时的视觉居中
    left_unit = 12 - half
    width = half * 2 * SCALE + SIDE * 2
    mid = -CAP / 2                                    # 大写线高的中点

    def tx(x): return (x - left_unit) * SCALE + SIDE
    def ty(y): return (y - 12) * SCALE + mid

    d = []
    for poly in polys:
        pts = poly[:-1] if poly[0] == poly[-1] else poly
        d.append("M" + " L".join(f"{fmt(tx(x))} {fmt(ty(y))}" for x, y in pts) + " Z")
    path = " ".join(d)

    guides = []
    for scale in ("S", "M", "L"):
        base = BASELINE[scale]
        guides.append(f'  <line id="Baseline-{scale}" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;" x1="263" x2="3036" y1="{fmt(base)}" y2="{fmt(base)}"/>')
        guides.append(f'  <line id="Capline-{scale}" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;" x1="263" x2="3036" y1="{fmt(base - CAP)}" y2="{fmt(base - CAP)}"/>')
    left, right = ORIGIN_X, ORIGIN_X + width
    guides.append(f'  <line id="left-margin-Regular-M" style="fill:none;stroke:#00AEEF;stroke-width:0.5;opacity:1.0;" x1="{fmt(left)}" x2="{fmt(left)}" y1="1030" y2="1150"/>')
    guides.append(f'  <line id="right-margin-Regular-M" style="fill:none;stroke:#00AEEF;stroke-width:0.5;opacity:1.0;" x1="{fmt(right)}" x2="{fmt(right)}" y1="1030" y2="1150"/>')

    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">
<svg version="1.1" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="3300" height="2200">
 <!--glyph: "{name}", point size: 100.0, generated by ios-native/scripts/icons/build-symbols.py-->
 <g id="Notes">
  <rect height="2200" id="artboard" style="fill:white;opacity:1" width="3300" x="0" y="0"/>
  <line style="fill:none;stroke:black;opacity:1;stroke-width:0.5;" x1="263" x2="3036" y1="292" y2="292"/>
  <text style="stroke:none;fill:black;font-family:sans-serif;font-size:13;font-weight:bold;" transform="matrix(1 0 0 1 263 322)">Weight/Scale Variations</text>
  <text style="stroke:none;fill:black;font-family:sans-serif;font-size:13;" transform="matrix(1 0 0 1 263 1156)">Medium</text>
  <text id="template-version" style="stroke:none;fill:black;font-family:sans-serif;font-size:13;text-anchor:end;" transform="matrix(1 0 0 1 3036 1933)">Template v.3.0</text>
  <text style="stroke:none;fill:black;font-family:sans-serif;font-size:13;text-anchor:end;" transform="matrix(1 0 0 1 3036 1951)">Requires Xcode 13 or greater</text>
  <text id="descriptive-name" style="stroke:none;fill:black;font-family:sans-serif;font-size:13;text-anchor:end;" transform="matrix(1 0 0 1 3036 1969)">{name}</text>
  <text style="stroke:none;fill:black;font-family:sans-serif;font-size:13;text-anchor:end;" transform="matrix(1 0 0 1 3036 1987)">Typeset at 100 points</text>
 </g>
 <g id="Guides">
{chr(10).join(guides)}
 </g>
 <g id="Symbols">
  <g id="Regular-M" transform="matrix(1 0 0 1 {fmt(left)} {fmt(BASELINE['M'])})">
   <path d="{path}"/>
  </g>
 </g>
</svg>
'''


def asset_name(key: str) -> str:
    # home_active → hp.home.active
    return "hp." + key.replace("_active", ".active")


def main() -> int:
    icons = load_icons()
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    (OUT / "Contents.json").write_text(json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n")
    count = 0
    for key, inner in icons.items():
        if key in SKIP:
            continue
        name = asset_name(key)
        polys = contours(raster(render_svg(inner)))
        if not polys:
            print(f"{key}: nothing rendered", file=sys.stderr)
            return 1
        folder = OUT / f"{name}.symbolset"
        folder.mkdir()
        (folder / f"{name}.svg").write_text(symbol_svg(name, polys))
        (folder / "Contents.json").write_text(json.dumps({
            "info": {"author": "xcode", "version": 1},
            "symbols": [{"filename": f"{name}.svg", "idiom": "universal"}],
        }, indent=2) + "\n")
        count += 1
    print(f"generated {count} symbols in {OUT.relative_to(HERE.parents[2])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
